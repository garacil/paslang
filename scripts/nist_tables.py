"""Generate pasnist's public basepoint multiples using SEC 1 section 2.2.1.

Curve parameters are SEC 2 sections 2.4.2 and 2.5.1. The P-256 layout is
Go's nistec/p256.go and p256_table_test.go: 43 six-bit affine windows.
P-384 keeps Go's 96 four-bit windows, storing affine X/Y instead of a
projective Z for each entry. Runtime selection reconstructs Z by a mask.
Only Python's integer arithmetic is used; there is no runtime dependency.
"""
import argparse
from pathlib import Path

BEGIN = "{ ---- generated by scripts/nist_tables.py: begin ---- }"
END = "{ ---- generated by scripts/nist_tables.py: end ---- }"
CURVES = {
    256: (
        0xffffffff00000001000000000000000000000000ffffffffffffffffffffffff,
        0x5ac635d8aa3a93e7b3ebbd55769886bc651d06b0cc53b0f63bce3c3e27d2604b,
        0x6b17d1f2e12c4247f8bce6e563a440f277037d812deb33a0f4a13945d898c296,
        0x4fe342e2fe1a7f9b8ee7eb4a7c0f9e162bce33576b315ececbb6406837bf51f5,
        43, 32, 6),
    384: (
        0xfffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffeffffffff0000000000000000ffffffff,
        0xb3312fa7e23ee7e4988e056be3f82d19181d9c6efe8141120314088f5013875ac656398d8a2ed19d2a85c8edd3ec2aef,
        0xaa87ca22be8b05378eb1c71ef320ad746e1d3b628ba79b9859f741e082542a385502f25dbf55296c3a545e3872760ab7,
        0x3617de4a96262c6f5d9e98bf9292dc29f8f41dbd289a147ce9da3113b5f0b8c00a60b1ce1d7e819d7a431d7c90ea0e5f,
        96, 15, 4),
}


def add(left, right, prime):
    """SEC 1's affine group law, for public generation data only."""
    if left is None:
        return right
    if right is None:
        return left
    x1, y1 = left
    x2, y2 = right
    if x1 == x2:
        if (y1 + y2) % prime == 0:
            return None
        slope = (3 * x1 * x1 - 3) * pow(2 * y1, -1, prime) % prime
    else:
        slope = (y2 - y1) * pow(x2 - x1, -1, prime) % prime
    x3 = (slope * slope - x1 - x2) % prime
    return x3, (slope * (x1 - x3) - y1) % prime


def tables(bits):
    prime, b, gx, gy, count, entries, shift = CURVES[bits]
    base = gx, gy
    result = []
    for _ in range(count):
        row = []
        point = None
        for _ in range(entries):
            point = add(point, base, prime)
            assert point is not None
            x, y = point
            assert (y * y - x * x * x + 3 * x - b) % prime == 0
            row.append(tuple(value * (1 << bits) % prime for value in point))
        result.append(row)
        for _ in range(shift):
            base = add(base, base, prime)
    return result


def limbs(value, bits):
    return tuple((value >> shift) & ((1 << 64) - 1)
                 for shift in range(0, bits, 64))


def raw(bits, data):
    return b"".join(value.to_bytes(bits // 8, "little")
                    for row in data for point in row for value in point)


def render():
    lines = [BEGIN, "const"]
    for bits in (256, 384):
        data = tables(bits)
        lines.append(f"  P{bits}GenTables: array[0..{len(data) - 1}] of TP{bits}AffineTable = (")
        for i, row in enumerate(data):
            lines.append("    (")
            for j, point in enumerate(row):
                fields = []
                for name, value in zip(("X", "Y"), point):
                    words = ", ".join("$%016X" % word for word in limbs(value, bits))
                    fields.append(f"{name}: ({words})")
                lines.append("      (" + "; ".join(fields) + ")" +
                             ("," if j + 1 < len(row) else ""))
            lines.append("    )" + ("," if i + 1 < len(data) else ""))
        lines.append("  );")
    lines.append(END)
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / "src/lib/pasnist.paslang"
    source = path.read_text()
    assert source.count(BEGIN) == source.count(END) == 1
    first, last = source.index(BEGIN), source.index(END) + len(END)
    generated = render()
    if args.check:
        if source[first:last] != generated:
            raise SystemExit("nist_tables: stale constants; run scripts/nist_tables.py")
        print("nist_tables: 1376 P-256 and 1440 P-384 affine points match SEC 1 arithmetic")
    else:
        path.write_text(source[:first] + generated + source[last:])


if __name__ == "__main__":
    main()
