"""Generate the PDF visual text classifier from pinned Unicode Bidi_Class data."""

import argparse
from hashlib import sha256
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'docs/ref/unicode/bidi-18.0.0/DerivedBidiClass.txt'
OUTPUT = ROOT / 'src/lib/paspdf.paslang'
DATA_SHA256 = 'd9e23222522551348ea1ccfbb4f62efbf98982afb95840f8959c08ed992c5607'
BRACKETS_SHA256 = '4b3b62e4a14b84ee752808c810c602534921c09a4a1bf78cfbee566d66c125b3'
START = '{ BEGIN GENERATED PDF BIDI PROPERTIES }\n'
END = '{ END GENERATED PDF BIDI PROPERTIES }'
KINDS = (
    ('bdNeutral', ()),
    ('bdLeft', ('L', 'Left_To_Right')),
    ('bdRight', ('R', 'AL', 'Right_To_Left', 'Arabic_Letter')),
    ('bdEuropeanNumber', ('EN',)),
    ('bdArabicNumber', ('AN',)),
    ('bdMark', ('NSM',)),
    ('bdEuropeanSeparator', ('ES',)),
    ('bdCommonSeparator', ('CS',)),
    ('bdTerminator', ('ET', 'European_Terminator')),
    ('bdControl', ('LRE', 'RLE', 'LRO', 'RLO', 'PDF', 'LRI', 'RLI', 'FSI', 'PDI')),
)
SPAN = re.compile(r'^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)')


def packed_rows(entries):
    return ',\n'.join('    ' + ', '.join(f'${value:08X}' for value in entries[i:i + 8])
                      for i in range(0, len(entries), 8))


def render(data, brackets):
    aliases = {name: i for i, (_, parts) in enumerate(KINDS) for name in parts}
    classes = bytearray(0x110000)
    lines = data.decode('utf-8').splitlines()
    # General and range-specific defaults precede explicit properties.
    ranges = [line.split('@missing:', 1)[1].strip() for line in lines if '# @missing:' in line]
    ranges += [line for line in lines if line and not line.startswith('#')]
    for row in ranges:
        match = SPAN.match(row)
        if not match:
            raise SystemExit(f'invalid Bidi_Class row {row!r}')
        low, high, kind = match.groups()
        first, last = int(low, 16), int(high or low, 16)
        classes[first:last + 1] = bytes([aliases.get(kind, 0)]) * (last - first + 1)

    entries = [(codepoint << 4) | kind for codepoint, kind in enumerate(classes)
               if codepoint == 0 or kind != classes[codepoint - 1]]
    pairs = {}
    for line in brackets.decode('utf-8').splitlines():
        if line and not line.startswith('#'):
            left, right, _ = line.split('#', 1)[0].split(';')
            source, peer = int(left, 16), int(right, 16)
            if max(source, peer) > 0xFFFF:
                raise SystemExit('PDF bidi bracket pair outside the BMP')
            if len(chr(source).encode('utf-8')) != len(chr(peer).encode('utf-8')):
                raise SystemExit('PDF bidi bracket pair has different byte lengths')
            pairs[source] = peer
    bracket_entries = [(cp << 16) | peer for cp, peer in sorted(pairs.items())]
    return (
        '{ Unicode 18.0.0 DerivedBidiClass and BidiBrackets, generated by scripts/gen_pdf_bidi.py.\n'
        '  Unicode data copyright 2026 Unicode, Inc.\n'
        '  See LICENSE-UNICODE for the Unicode license terms. }\n'
        'type\n  TPdfBidiClass = (' + ', '.join(item[0] for item in KINDS[:5]) + ',\n    '
        + ', '.join(item[0] for item in KINDS[5:]) + ');\n\n'
        f'const\n  PdfBidiRanges: array[0..{len(entries) - 1}] of UInt32 = (\n'
        + packed_rows(entries) + ');\n'
        f'  PdfBidiBrackets: array[0..{len(bracket_entries) - 1}] of UInt32 = (\n'
        + packed_rows(bracket_entries) + ');\n'
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data', type=Path, default=DATA)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--write', action='store_true')
    mode.add_argument('--check', action='store_true')
    args = parser.parse_args()
    brackets_path = args.data.with_name('BidiBrackets.txt')
    if args.check and (not args.data.exists() or not brackets_path.exists()):
        print('gen_pdf_bidi.py: pinned Unicode reference data is unavailable')
        return
    data = args.data.read_bytes()
    if sha256(data).hexdigest() != DATA_SHA256:
        raise SystemExit('DerivedBidiClass is not the pinned Unicode 18.0.0 file')
    brackets = brackets_path.read_bytes()
    if sha256(brackets).hexdigest() != BRACKETS_SHA256:
        raise SystemExit('BidiBrackets is not the pinned Unicode 18.0.0 file')
    text = OUTPUT.read_text()
    prefix, rest = text.split(START, 1)
    previous, suffix = rest.split(END, 1)
    wanted = render(data, brackets)
    if args.write:
        OUTPUT.write_text(prefix + START + wanted + END + suffix)
    elif previous != wanted:
        raise SystemExit('generated PDF bidi properties differ')
    print('PDF bidi properties match Unicode 18.0.0')


if __name__ == '__main__':
    main()
