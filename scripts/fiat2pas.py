# Translates fiat-crypto's Go field code for P-256 and P-384 (Go 1.27.3,
# crypto/internal/fips140/nistec/fiat/p256_fiat64.go and p384_fiat64.go)
# into paslang, statement by statement, and puts it into pasnist.paslang
# between the markers
#   { ---- generated by fiat2pas.py from pNNN_fiat64.go: begin ---- }
#   { ---- generated by fiat2pas.py from pNNN_fiat64.go: end ---- }
# and the addition chains between
#   { ---- generated by fiat2pas.py from the addition chains: begin ---- }
#   { ---- generated by fiat2pas.py from the addition chains: end ---- }
# Deterministic: the same Go file gives the same paslang text.
# Usage: fiat2pas.py pasnist.paslang   (no argument: print the text)
#
# MODE = 'alu' (the one used), statement by statement:
#   hi, lo = bits.Mul64(a, b)       hi := MulHi(a, b); lo := a * b
#   _, lo = bits.Mul64(a, b)        lo := a * b
#   s, c = bits.Add64(a, b, cin)    s := a + b + cin;
#                                   c := ((a and b) or ((a or b) and (not s))) shr 63
#   d, c = bits.Sub64(a, b, bin)    d := a - b - bin;
#                                   c := (((not a) and b) or ((not (a xor b)) and d)) shr 63
#     (the carry and the borrow as math/bits.go's own Add64 and Sub64
#     write them: no flags, constant time)
#   cmovznzU64(&o, c, a, b)         m := c * -1; o := (m and b) or ((not m) and a)
#   uint64(...), pNNNUint1(...)     dropped (every value is a 64-bit Integer)
#   & | ^x >> <<                    and or not shr shl
#   0x...                           $...
# and then (SLOTS) fiat's single-assignment names x1, x2, ... are given a
# few words r0, r1, ... by liveness (allocate below), the Go name kept in
# a comment on each line. Both choices are for the code paslangc 1.1.287
# makes: a carry out of AddCarry is a variable whose address is taken
# and lives in memory, and a routine of hundreds of locals keeps few in
# registers; together they make P-256's multiplication twice as fast.
# MODE = 'words' gives the direct mapping (Mul128, AddCarry, SubBorrow)
# with fiat's own names, slower, kept to compare.
import re
import sys

GO = '/usr/lib/go/src/crypto/internal/fips140/nistec/fiat/%s_fiat64.go'
MODE = 'alu'
SLOTS = True

VAR = re.compile(r'\b(x\d+|(?:ya|yb|cm|xd)_\d+)\b')


def allocate(lines):
    # Straight-line code: every value of fiat's (x1, x2, ...) gets one of
    # a few words, r0, r1, ..., by a linear scan over the statements:
    # a word is free again after the last statement that reads its value,
    # and the statement's own result may take it at once (the right side
    # is read before the left is written). The Go name stays in a
    # comment, so each line still says which statement of Go it is.
    # the helpers xd, ya, yb and cm are written many times: each writing
    # becomes a name of its own first, so that each has one life
    ver, ssa = {}, []
    cur = lambda m: '%s_%d' % (m.group(1), ver[m.group(1)])
    for l in lines:
        m = re.match(r'(xd|ya|yb|cm) := (.*);$', l)
        if m:
            rhs = re.sub(r'\b(xd|ya|yb|cm)\b', cur, m.group(2))
            ver[m.group(1)] = ver.get(m.group(1), 0) + 1
            l = '%s_%d := %s;' % (m.group(1), ver[m.group(1)], rhs)
        else:
            l = re.sub(r'\b(xd|ya|yb|cm)\b', cur, l)
        ssa.append(l)
    lines = ssa
    defs, uses = [], []
    for l in lines:
        m = re.match(r'(\w+) := (.*);$', l)
        if m and VAR.fullmatch(m.group(1)):
            d = [m.group(1)]
            u = VAR.findall(m.group(2))
        else:
            m = re.match(r'Mul128\((.*), (\w+), (\w+)\);$', l)
            if m:
                d = [m.group(2), m.group(3)]
                u = VAR.findall(m.group(1))
            else:
                d = []
                u = VAR.findall(l)
        defs.append(d)
        uses.append(u)
    last = {}
    for i, u in enumerate(uses):
        for v in u:
            last[v] = i
    free, where, nslot, out = [], {}, 0, []
    for i, l in enumerate(lines):
        for v in set(uses[i]):
            if v not in where:
                raise SystemExit('read before written: ' + v)
        for v in set(uses[i]):
            if last[v] == i and v not in defs[i]:
                free.append(where[v])
        free.sort(reverse=True)
        names = {}
        for v in uses[i]:
            names[v] = where[v]
        for v in defs[i]:
            if free:
                r = free.pop()
            else:
                r = 'r%d' % nslot
                nslot += 1
            where[v] = r
            if last.get(v, -1) <= i:
                free.append(r)
                free.sort(reverse=True)
        # rename: the right side with the old homes, the left with the new
        m = re.match(r'(\w+) := (.*);$', l)
        if m and VAR.fullmatch(m.group(1)):
            rhs = VAR.sub(lambda mm: names[mm.group(1)], m.group(2))
            text = '%s := %s;' % (where[m.group(1)], rhs)
            if re.match(r'x\d+$', m.group(1)):
                text += '  { %s }' % m.group(1)
        else:
            m = re.match(r'Mul128\((.*), (\w+), (\w+)\);$', l)
            if m:
                text = 'Mul128(%s, %s, %s);  { %s, %s }' % (
                    VAR.sub(lambda mm: names[mm.group(1)], m.group(1)),
                    where[m.group(2)], where[m.group(3)], m.group(2), m.group(3))
            else:
                text = VAR.sub(lambda mm: names[mm.group(1)], l)
        out.append(text)
    return out, ['r%d' % k for k in range(nslot)]

WANT = ['Mul', 'Square', 'Add', 'Sub', 'SetOne', 'FromMontgomery',
        'ToMontgomery', 'Selectznz', 'ToBytes', 'FromBytes']


def expr(e, curve):
    e = e.strip()
    # casts that change nothing for 64-bit words
    prev = None
    while prev != e:
        prev = e
        e = re.sub(r'uint64\(%sUint1\((x\d+)\)\)' % curve, r'\1', e)
        e = re.sub(r'%sUint1\((x\d+)\)' % curve, r'\1', e)
        e = re.sub(r'uint64\((0x[0-9a-f]+)\)', r'\1', e)
        e = re.sub(r'uint64\((x\d+|arg\d(\[\d+\])?)\)', r'\1', e)
    if 'uint64(' in e or 'Uint1' in e:
        raise SystemExit('cannot translate: ' + e)
    # uint8(x) & 0xff and uint8((x >> 8)): the low byte
    e = re.sub(r'\(uint8\((x\d+)\) & 0xff\)', r'(\1 and $FF)', e)
    e = re.sub(r'^uint8\(\((x\d+) >> 8\)\)$', r'((\1 shr 8) and $FF)', e)
    if 'uint8' in e:
        raise SystemExit('cannot translate: ' + e)
    e = re.sub(r'0x([0-9a-f]+)', lambda m: '$' + m.group(1).upper(), e)
    e = e.replace('(^', '(not ')
    e = e.replace(' & ', ' and ').replace(' | ', ' or ')
    e = e.replace(' >> ', ' shr ').replace(' << ', ' shl ')
    if re.search(r'[&|^]', e):
        raise SystemExit('cannot translate: ' + e)
    return e


def split_args(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch == ',' and depth == 0:
            out.append(cur)
            cur = ''
            continue
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        cur += ch
    out.append(cur)
    return [a.strip() for a in out]


def translate(curve):
    src = open(GO % curve).read()
    n = 4 if curve == 'p256' else 6
    nb = 32 if curve == 'p256' else 48
    fe = 'T%sFe' % curve.upper()
    raw = 'T%sRaw' % curve.upper()
    funcs = {}
    for m in re.finditer(r'^func %s(\w+)\((.*?)\) \{\n(.*?)^\}' % curve, src, re.S | re.M):
        funcs[m.group(1)] = (m.group(2), m.group(3))
    pre = curve.upper()
    text = []
    for name in WANT:
        params, body = funcs[name]
        # the head
        if name in ('Mul', 'Add', 'Sub'):
            head = 'procedure %s%s(var Out1: %s; const Arg1, Arg2: %s);' % (pre, name, fe, fe)
        elif name in ('Square', 'FromMontgomery', 'ToMontgomery'):
            head = 'procedure %s%s(var Out1: %s; const Arg1: %s);' % (pre, name, fe, fe)
        elif name == 'SetOne':
            head = 'procedure %s%s(var Out1: %s);' % (pre, name, fe)
        elif name == 'Selectznz':
            head = 'procedure %s%s(var Out1: %s; Arg1: Integer; const Arg2, Arg3: %s);' % (pre, name, fe, fe)
        elif name == 'ToBytes':
            head = 'procedure %s%s(var Out1: %s; const Arg1: %s);' % (pre, name, raw, fe)
        elif name == 'FromBytes':
            head = 'procedure %s%s(var Out1: %s; const Arg1: %s);' % (pre, name, fe, raw)
        lines = []
        names = []
        dummy = False
        cm = False
        temps = set()
        for st in body.split('\n'):
            st = st.strip()
            if not st or st.startswith('//'):
                continue
            m = re.match(r'var (x\d+) uint64$', st)
            if m:
                continue
            m = re.match(r'(_|x\d+), (_|x\d+) = bits\.(Mul64|Add64|Sub64)\((.*)\)$', st)
            if m:
                a, b, op, args = m.group(1), m.group(2), m.group(3), split_args(m.group(4))
                args = [expr(x, curve) for x in args]
                for v in (a, b):
                    if v != '_' and v not in names:
                        names.append(v)
                if op == 'Mul64':
                    if a == '_':
                        lines.append('%s := %s * %s;' % (b, args[0], args[1]))
                    elif MODE == 'words':
                        lines.append('Mul128(%s, %s, %s, %s);' % (args[0], args[1], a, b))
                    else:
                        lines.append('%s := MulHi(%s, %s);' % (a, args[0], args[1]))
                        lines.append('%s := %s * %s;' % (b, args[0], args[1]))
                elif MODE == 'words':
                    word = 'AddCarry' if op == 'Add64' else 'SubBorrow'
                    if a == '_':
                        a = 'xd'
                        dummy = True
                    if b == '_':
                        b = 'xd'
                        dummy = True
                    lines.append('%s := %s(%s, %s, %s, %s);' % (a, word, args[0], args[1], args[2], b))
                else:
                    # math/bits' own Add64 and Sub64 (bits.go): the carry
                    # or borrow out from the top bits, no flags
                    ops = []
                    for k, x in enumerate(args[:2]):
                        if re.match(r'^(x\d+|\$[0-9A-F]+|arg\d\[\d+\])$', x):
                            ops.append(x)
                        else:
                            t = 'ya' if k == 0 else 'yb'
                            temps.add(t)
                            lines.append('%s := %s;' % (t, x))
                            ops.append(t)
                    x, y = ops
                    cin = args[2]
                    if a == '_':
                        a = 'xd'
                        dummy = True
                    if op == 'Add64':
                        lines.append('%s := %s + %s + %s;' % (a, x, y, cin))
                        if b != '_':
                            lines.append('%s := ((%s and %s) or ((%s or %s) and (not %s))) shr 63;' % (b, x, y, x, y, a))
                    else:
                        lines.append('%s := %s - %s - %s;' % (a, x, y, cin))
                        if b != '_':
                            lines.append('%s := (((not %s) and %s) or ((not (%s xor %s)) and %s)) shr 63;' % (b, x, y, x, y, a))
                continue
            m = re.match(r'%sCmovznzU64\(&(x\d+), (.*)\)$' % curve, st)
            if m:
                o = m.group(1)
                c, a2, a3 = [expr(x, curve) for x in split_args(m.group(2))]
                if o not in names:
                    names.append(o)
                cm = True
                lines.append('cm := %s * $FFFFFFFFFFFFFFFF;' % c)
                lines.append('%s := (cm and %s) or ((not cm) and %s);' % (o, a3, a2))
                continue
            m = re.match(r'(x\d+) := (.*)$', st)
            if m:
                v = m.group(1)
                if v not in names:
                    names.append(v)
                e = m.group(2)
                if re.match(r'arg1\[\d+\]$', e) and name == 'FromBytes':
                    e = 'Integer(%s)' % e
                elif re.match(r'\(uint64\(arg1\[\d+\]\) << \d+\)$', e):
                    e = re.sub(r'\(uint64\((arg1\[\d+\])\) << (\d+)\)', r'(Integer(\1) shl \2)', e)
                lines.append('%s := %s;' % (v, expr(e, curve)))
                continue
            m = re.match(r'out1\[(\d+)\] = (.*)$', st)
            if m:
                v = expr(m.group(2), curve)
                if name == 'ToBytes':
                    v = 'Byte(%s)' % v
                lines.append('Out1[%s] := %s;' % (m.group(1), v))
                continue
            raise SystemExit('cannot translate statement: ' + st)
        if SLOTS and MODE == 'alu':
            lines, slots = allocate(lines)
            names = slots
            dummy = cm = False
            temps = set()
        decl = list(names)
        if dummy:
            decl.append('xd')
        if cm:
            decl.append('cm')
        decl.extend(sorted(temps))
        vs = []
        row = '  '
        for i, v in enumerate(decl):
            piece = v + (', ' if i < len(decl) - 1 else ': Integer;')
            if len(row) + len(piece) > 76:
                vs.append(row.rstrip())
                row = '  '
            row += piece
        vs.append(row)
        text.append('{ %s%s, as fiat-crypto\'s %s%s in Go\'s fiat/%s_fiat64.go }' % (pre, name, curve, name, curve))
        text.append(head)
        if decl:
            text.append('var')
            text.extend(vs)
        text.append('begin')
        text.extend('  ' + l for l in lines)
        text.append('end;')
        text.append('')
    return '\n'.join(text)


# The addition chains (exponentiations by p - 2 and by (p + 1) / 4) of
#   fiat/p256_invert.go Invert, fiat/p384_invert.go Invert,
#   p256.go p256Sqrt (up to its check) and p384.go p384SqrtCandidate
# translated statement by statement:
#   a.Square(b)            PxxxSquare(a, b)
#   a.Mul(b, c)            PxxxMul(a, b, c)
#   p256Square(a, b, n)    P256SquareN(a, b, n)   (p256.go p256Square)
#   for s := k; s < m; s++ { st }    for s := k to m - 1 do st
CHAINS = [
    # (Go file, Go function, paslang head, locals, result statement, comment)
    ('fiat/p256_invert.go', r'func \(e \*P256Element\) Invert\(x \*P256Element\) \*P256Element',
     'procedure P256FeInvert(var E: TP256Fe; const X: TP256Fe);', 'z, t0, t1: TP256Fe;', 'E := z;',
     'P256FeInvert sets E = 1/X (0 for 0) by the addition chain of Go\'s\n  fiat/p256_invert.go Invert, the exponent p - 2'),
    ('fiat/p384_invert.go', r'func \(e \*P384Element\) Invert\(x \*P384Element\) \*P384Element',
     'procedure P384FeInvert(var E: TP384Fe; const X: TP384Fe);', 'z, t0, t1, t2, t3: TP384Fe;', 'E := z;',
     'P384FeInvert sets E = 1/X (0 for 0) by the addition chain of Go\'s\n  fiat/p384_invert.go Invert, the exponent p - 2'),
    ('p256.go', r'func p256Sqrt\(e, x \*fiat.P256Element\) \(isSquare bool\)',
     'procedure P256SqrtCandidate(var Z: TP256Fe; const X: TP256Fe);', 't0, t1: TP256Fe;', 'Z := t0;',
     'P256SqrtCandidate sets Z = X^((p + 1) / 4), a square root of X when\n  X has one, by the addition chain of Go\'s p256.go p256Sqrt (the\n  part before its check)'),
    ('p384.go', r'func p384SqrtCandidate\(z, x \*fiat.P384Element\)',
     'procedure P384SqrtCandidate(var Z: TP384Fe; const X: TP384Fe);', 't0, t1, t2: TP384Fe;', '',
     'P384SqrtCandidate sets Z = X^((p + 1) / 4), a square root of X when\n  X has one, by the addition chain of Go\'s p384.go p384SqrtCandidate;\n  Z and X must not be the same variable'),
]


def translate_chain(goname, sig, head, locals_, last, comment):
    src = open('/usr/lib/go/src/crypto/internal/fips140/nistec/' + goname).read()
    m = re.search(sig + r' \{\n(.*?)^\}', src, re.S | re.M)
    body = m.group(1)
    pre = 'P256' if 'P256' in head else 'P384'
    out = []
    loop = None
    for st in body.split('\n'):
        st = st.strip()
        if st.startswith('// Check if'):
            break
        if not st or st.startswith('//') or st.startswith('var ') or ':= new(' in st:
            continue
        if st.startswith('return'):
            break
        mm = re.match(r'for s := (\d+); s < (\d+); s\+\+ \{$', st)
        if mm:
            loop = 'for s := %s to %d do ' % (mm.group(1), int(mm.group(2)) - 1)
            continue
        if st == '}':
            loop = None
            continue
        mm = re.match(r'(\w+)\.Square\((\w+)\)$', st)
        if mm:
            call = '%sSquare(%s, %s);' % (pre, mm.group(1), mm.group(2))
        else:
            mm = re.match(r'(\w+)\.Mul\((\w+), (\w+)\)$', st)
            if mm:
                call = '%sMul(%s, %s, %s);' % (pre, mm.group(1), mm.group(2), mm.group(3))
            else:
                mm = re.match(r'p256Square\((\w+), (\w+), (\d+)\)$', st)
                if not mm:
                    raise SystemExit('cannot translate chain statement: ' + st)
                call = 'P256SquareN(%s, %s, %s);' % (mm.group(1), mm.group(2), mm.group(3))
        out.append('  ' + (loop or '') + call)
    text = ['{ %s }' % comment, head, 'var', '  ' + locals_, '  s: Integer;', 'begin']
    text += out
    if last:
        text.append('  ' + last)
    text += ['end;', '']
    return '\n'.join(text)


def chains():
    return '\n'.join(translate_chain(*c) for c in CHAINS)


def splice(path, curve, frag):
    begin = '{ ---- generated by fiat2pas.py from %s: begin ---- }' % curve
    end = '{ ---- generated by fiat2pas.py from %s: end ---- }' % curve
    s = open(path).read()
    i = s.index(begin) + len(begin)
    j = s.index(end)
    s = s[:i] + '\n\n' + frag + '\n' + s[j:]
    open(path, 'w').write(s)


if __name__ == '__main__':
    target = sys.argv[1] if len(sys.argv) > 1 else None
    for c in ('p256', 'p384'):
        f = translate(c)
        if target:
            splice(target, c + '_fiat64.go', f)
        else:
            print(f)
    f = chains()
    if target:
        splice(target, 'the addition chains', f)
    else:
        print(f)
